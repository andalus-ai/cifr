package tech.kayys.aljabr.engine.tool.generate;

import io.smallrye.mutiny.Uni;
import jakarta.enterprise.context.ApplicationScoped;
import tech.kayys.aljabr.engine.tool.*;

import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.List;
import java.util.Map;
import java.util.Set;

@ApplicationScoped
public class GenerateTool implements AljabrTool {

    private static final Path WORKSPACE_ROOT = Paths.get(System.getProperty("user.dir"));

    @Override
    public ToolDescriptor descriptor() {
        return new ToolDescriptor(
            "generate",
            "Generate boilerplate code, tests, or project structure.",
            ToolCategory.CODE_ANALYSIS,
            Map.of(
                "type", "object",
                "properties", Map.of(
                    "type", Map.of("type", "string", "description", "Generation type: class, test, endpoint, schema, etc."),
                    "name", Map.of("type", "string", "description", "Name of the item to generate"),
                    "path", Map.of("type", "string", "description", "Where to generate"),
                    "template", Map.of("type", "string", "description", "Template to use"),
                    "parameters", Map.of("type", "object", "description", "Template parameters")
                ),
                "required", List.of("type", "name")
            ),
            Set.of(ToolCapability.WRITE, ToolCapability.MUTATES_WORKSPACE),
            ToolRisk.MEDIUM
        );
    }

    @Override
    @SuppressWarnings("unchecked")
    public Uni<ToolResult> execute(ToolRequest request, ToolExecutionContext context) {
        return Uni.createFrom().item(() -> {
            try {
                String type = (String) request.arguments().get("type");
                String name = (String) request.arguments().get("name");
                String pathStr = (String) request.arguments().get("path");
                String template = (String) request.arguments().get("template");
                Map<String, Object> params = (Map<String, Object>) request.arguments().get("parameters");

                if (type == null || type.isBlank() || name == null || name.isBlank()) {
                    return new GenerateResult(false, "Type and name are required");
                }

                Path targetPath = pathStr != null 
                    ? WORKSPACE_ROOT.resolve(pathStr).normalize()
                    : WORKSPACE_ROOT.resolve(name);

                if (!targetPath.startsWith(WORKSPACE_ROOT)) {
                    return new GenerateResult(false, "Access denied");
                }

                if (targetPath.getParent() != null) {
                    Files.createDirectories(targetPath.getParent());
                }

                String content = generateContent(type, name, params, template);
                Files.writeString(targetPath, content);

                return new GenerateResult(true, "Generated " + type + " at " + targetPath, targetPath.toString());

            } catch (Exception e) {
                return new GenerateResult(false, "Error: " + e.getMessage());
            }
        });
    }

    private String generateContent(String type, String name, Map<String, Object> params, String template) {
        String className = capitalize(name);
        String packageName = params != null && params.containsKey("package") 
            ? (String) params.get("package") 
            : "tech.kayys.aljabr";

        return switch (type.toLowerCase()) {
            case "class" -> """
                package %s;

                public class %s {
                    // Generated by Aljabr
                }
                """.formatted(packageName, className);
            case "test" -> """
                package %s;

                import org.junit.jupiter.api.Test;
                import static org.junit.jupiter.api.Assertions.*;

                class %sTest {
                    @Test
                    void testExecution() {
                        assertTrue(true);
                    }
                }
                """.formatted(packageName, className);
            case "endpoint" -> """
                package %s.controller;

                import jakarta.ws.rs.*;
                import jakarta.ws.rs.core.MediaType;
                import jakarta.ws.rs.core.Response;

                @Path("/api/%s")
                @Produces(MediaType.APPLICATION_JSON)
                @Consumes(MediaType.APPLICATION_JSON)
                public class %sResource {
                    @GET
                    public Response get() {
                        return Response.ok().build();
                    }
                }
                """.formatted(packageName, name.toLowerCase(), className);
            default -> "// Generated content for " + type + " " + name;
        };
    }

    private String capitalize(String s) {
        if (s == null || s.isEmpty()) return s;
        return s.substring(0, 1).toUpperCase() + s.substring(1);
    }
}
